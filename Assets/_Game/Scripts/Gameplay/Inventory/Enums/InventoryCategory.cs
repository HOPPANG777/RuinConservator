/// <summary>
/// 인벤토리 UI의 카테고리 필터 종류입니다.
/// </summary>
public enum InventoryCategory
{
    // 문서 기준 1~6번 아이템 타입을 표시하는 기본 카테고리입니다.
    INVENTORY_CATEGORY_ALL = 0,

    // 문서 기준 2~3번인 술 수집형 아이템과 술 도구 아이템을 표시하는 카테고리입니다.
    INVENTORY_CATEGORY_ALCOHOL = 1,

    // 문서 기준 4~5번인 유물 수집형 아이템과 유물 도구 아이템을 표시하는 카테고리입니다.
    INVENTORY_CATEGORY_RELIC = 2,

    // 문서 기준 6번인 기타 아이템만 표시하는 카테고리입니다.
    INVENTORY_CATEGORY_MISC = 3
}
