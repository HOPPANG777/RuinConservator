//==============================================================================

/// <summary>
/// 인벤토리 아이템의 용도별 종류입니다.
/// </summary>
public enum ItemType
{
    // 문서 기준 1번 타입입니다. 퀘스트 진행 조건, 퀘스트 보상, NPC 전달 등에 사용하는 아이템입니다.
    ITEM_QUEST = 0,

    // 문서 기준 2번 타입입니다. 술 조제 콘텐츠에서 완성된 술 또는 재료처럼 수집 대상으로 사용하는 아이템입니다.
    ITEM_ALCOHOL_COLLECTIBLE = 1,

    // 문서 기준 3번 타입입니다. 술 조제 콘텐츠에서 술을 만들 때 사용하는 도구 아이템입니다.
    ITEM_ALCOHOL_TOOL = 2,

    // 문서 기준 4번 타입입니다. 유물 발굴 콘텐츠에서 발굴 완료한 유물처럼 수집 대상으로 사용하는 아이템입니다.
    ITEM_RELIC_COLLECTIBLE = 3,

    // 문서 기준 5번 타입입니다. 유물 발굴 콘텐츠에서 유물을 발굴할 때 사용하는 도구 아이템입니다.
    ITEM_RELIC_TOOL = 4,

    // 문서 기준 6번 타입입니다. 위 분류에 해당하지 않는 기타 아이템입니다.
    ITEM_MISC = 5
}
