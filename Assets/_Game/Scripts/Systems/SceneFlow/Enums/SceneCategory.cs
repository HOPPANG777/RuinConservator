/// <summary>
/// 씬의 역할을 구분하기 위한 고정 분류 열거형입니다.
/// </summary>
public enum SceneCategory
{
    // 분류되지 않은 기본값입니다.
    NONE = 0,

    // 시스템 매니저가 상주하는 상시 씬(Scene_Persistent 등)입니다.
    SYSTEM,

    // 실제 게임 플레이가 진행되는 스테이지 씬입니다.
    STAGE
}
